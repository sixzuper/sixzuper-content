# Add scripts directory to path
sys.path.insert(0, str(Path(__file__).parent))

# Load environment
def load_env():
    env = {}
    env_path = Path.home() / ".hermes" / ".env"
    if env_path.exists():
        with open(env_path) as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    env[k.strip()] = v.strip()
    return env

