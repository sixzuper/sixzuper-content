def main():
    parser = argparse.ArgumentParser(description="SixZuper IG Edukasi Dry Run Publisher")
    parser.add_argument("--tip", type=str, help="Custom tech tip text")
    parser.add_argument("--random-tip", action="store_true", help="Use random tip from database")
    
    args = parser.parse_args()
    
    # Load environment
    env = load_env()
    
    # Get tip text
    if args.tip:
        tip_text = args.tip
    elif args.random_tip:
        from tips_database import get_todays_tip
        tip_text = get_todays_tip()
    else:
        # Default fallback
        tip_text = "Gunakan .env untuk konfigurasi — jangan hardcoded values!"
    
    print(f"📝 Generating post for tip: {tip_text}")
    
    # Generate content
    output_file = generate_quote_card(tip_text)
    print(f"📤 Generated: {output_file}")
    
    # Simulate CDN upload
    cdn_url, upload_status = simulate_cdn_upload(output_file)
    print(f"📡 CDN URL: {cdn_url} ({upload_status})")
    
    # Build caption
    caption, hashtags = build_caption(tip_text)
    print(f"📄 Caption length: {len(caption)} chars")
    
    # Log attempt
    entry = log_post_attempt(caption, cdn_url)
    print(f"📝 Logged to publish_log.jsonl")
    
    # Print Telegram summary
    summary = print_telegram_summary(tip_text, caption, cdn_url, output_file)
    
    # Save summary for reference
    summary_path = Path(output_file).parent / f"summary_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    with open(summary_path, "w") as f:
        json.dump({
            "tip": tip_text,
            "caption": caption,
            "cdn_url": cdn_url,
            "file_path": output_file,
            "hashtags": hashtags,
            "status": "dry_run",
            "timestamp": datetime.now().isoformat()
        }, f, indent=2)
    
    print(f"\n✅ Dry run complete. Files saved to {Path(output_file).parent}")

if __name__ == "__main__":
    main()