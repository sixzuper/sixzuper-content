def simulate_cdn_upload(file_path):
    """Simulate uploading to CDN (GitHub Pages)."""
    # In dry-run mode, skip actual upload
    # Return simulated CDN URL
    filename = Path(file_path).name
    cdn_url = f"https://raw.githubusercontent.com/sixzuper/sixzuper-content/main/drafts/{filename}"
    return cdn_url, "simulated"

def build_caption(tip_text):
    """Build full Instagram caption with hashtags."""
    hashtags = [
        "#TechTips", "#SixzuperLabs", "#LearnWithAI",
        "#WebDev", "#Laravel", "#TechEducation"
    ]
    
    caption = f"""💡 SixZuper Daily Tech Tip

{tip_text}

.
.
.
#TechTips #SixzuperLabs #LearnWithAI #WebDev #Laravel"""
    
    return caption, hashtags

def log_post_attempt(caption, cdn_url, status="dry_run", notes=None):
    """Log post attempt to publish_log.jsonl."""
    log_path = Path.home() / "sixzuper-content" / "publish_log.jsonl"
    entry = {
        "timestamp": datetime.now().isoformat(),
        "caption_preview": caption[:100],
        "cdn_url": cdn_url,
        "status": status,
        "notes": notes or "Dry run simulation - no actual IG publish"
    }
    
    with open(log_path, "a") as f:
        f.write(json.dumps(entry) + "\n")
    
    return entry

